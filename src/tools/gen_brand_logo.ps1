# gen_brand_logo.ps1
# Converts a PNG into Ext/Includes/ImGui/BrandLogo.hpp as
#   inline unsigned char brand_logo[<N>] = { 0x.., ... };
# Requires only .NET (System.Drawing / System.IO). No external deps.
#
# Usage:
#   pwsh -File tools\gen_brand_logo.ps1 -In "C:\path\logo.png" -Out "Ext\Includes\ImGui\BrandLogo.hpp"

param(
    [Parameter(Mandatory = $true)][string]$In,
    [Parameter(Mandatory = $true)][string]$Out,
    [int]$MaxDim = 512,
    [int]$BytesPerLine = 12
)

Add-Type -AssemblyName System.Drawing

$src = (Resolve-Path -LiteralPath $In).Path
$img = [System.Drawing.Image]::FromFile($src)

# --- resize preserving aspect ratio, never upscaling ---
$w = $img.Width
$h = $img.Height
$scale = 1.0
if ([Math]::Max($w, $h) -gt $MaxDim) {
    $scale = $MaxDim / [double]([Math]::Max($w, $h))
}
$nw = [int][Math]::Round($w * $scale)
$nh = [int][Math]::Round($h * $scale)
if ($nw -lt 1) { $nw = 1 }
if ($nh -lt 1) { $nh = 1 }

$bmp = New-Object System.Drawing.Bitmap($nw, $nh, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
$g = [System.Drawing.Graphics]::FromImage($bmp)
$g.CompositingMode = [System.Drawing.Drawing2D.CompositingMode]::SourceCopy
$g.CompositingQuality = [System.Drawing.Drawing2D.CompositingQuality]::HighQuality
$g.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
$g.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
$g.DrawImage($img, 0, 0, $nw, $nh)
$g.Dispose()
$img.Dispose()

# --- lock bits and copy BGRA (D3DX11 loads PNG; we re-encode as PNG) ---
$rect = New-Object System.Drawing.Rectangle(0, 0, $nw, $nh)
$data = $bmp.LockBits($rect, [System.Drawing.Imaging.ImageLockMode]::ReadOnly, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
$stride = $data.Stride
$len = $stride * $nh
$buf = New-Object byte[] $len
[System.Runtime.InteropServices.Marshal]::Copy($data.Scan0, $buf, 0, $len)
$bmp.UnlockBits($data)

# --- rebuild a tightly packed ARGB bitmap (stride may exceed width*4) ---
$bmp2 = New-Object System.Drawing.Bitmap($nw, $nh, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
$d2 = $bmp2.LockBits($rect, [System.Drawing.Imaging.ImageLockMode]::WriteOnly, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
$s2 = $d2.Stride
for ($y = 0; $y -lt $nh; $y++) {
    $row = New-Object byte[] ($nw * 4)
    [Array]::Copy($buf, $y * $stride, $row, 0, $nw * 4)
    [System.Runtime.InteropServices.Marshal]::Copy($row, 0, [IntPtr]::Add($d2.Scan0, $y * $s2), $nw * 4)
}
$bmp2.UnlockBits($d2)

# --- encode to PNG ---
$ms = New-Object System.IO.MemoryStream
$bmp2.Save($ms, [System.Drawing.Imaging.ImageFormat]::Png)
$bmp2.Dispose()
$bytes = $ms.ToArray()
$ms.Dispose()

# --- emit header ---
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('#pragma once')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('// Generated by tools/gen_brand_logo.ps1 - do not hand-edit.')
[void]$sb.AppendLine("// Source: $([System.IO.Path]::GetFileName($src))  ${nw}x${nh}  PNG  $($bytes.Length) bytes")
[void]$sb.AppendLine('')
[void]$sb.AppendLine("inline unsigned char brand_logo [$($bytes.Length)] = {")

for ($i = 0; $i -lt $bytes.Length; $i += $BytesPerLine) {
    $end = [Math]::Min($i + $BytesPerLine, $bytes.Length) - 1
    $parts = @()
    for ($j = $i; $j -le $end; $j++) {
        $parts += ('0x{0:X2}' -f $bytes[$j])
    }
    [void]$sb.AppendLine('    ' + ($parts -join ', ') + ',')
}
[void]$sb.AppendLine('};')

$outPath = [System.IO.Path]::GetFullPath((Join-Path (Get-Location) $Out))
$outDir = [System.IO.Path]::GetDirectoryName($outPath)
if (!(Test-Path -LiteralPath $outDir)) { New-Item -ItemType Directory -Path $outDir -Force | Out-Null }
[System.IO.File]::WriteAllText($outPath, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))

Write-Output "wrote $outPath  (${nw}x${nh}, $($bytes.Length) bytes)"
